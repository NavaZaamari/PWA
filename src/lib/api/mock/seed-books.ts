import type { Book, CoverMotif } from "../types";

type RawBook = Omit<Book, "ratingDistribution" | "cover"> & { motif: CoverMotif };

/** Deterministic 1..5 star distribution that matches the average. */
export function distributionFor(avg: number, count: number): Book["ratingDistribution"] {
  // Weight each star by closeness to the average (sharper for high averages).
  const weights = [1, 2, 3, 4, 5].map((s) => Math.exp(-Math.pow(s - avg, 2) / 1.1));
  const sum = weights.reduce((a, b) => a + b, 0);
  const counts = weights.map((w) => Math.round((w / sum) * count));
  const diff = count - counts.reduce((a, b) => a + b, 0);
  const k = Math.min(4, Math.max(0, Math.round(avg) - 1));
  counts[k] = (counts[k] ?? 0) + diff;
  return counts as Book["ratingDistribution"];
}

